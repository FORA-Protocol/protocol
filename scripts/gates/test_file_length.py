"""Tests for file_length.py, run through its command line and through ratchet.py.

Each test copies the gate modules into a throwaway git repository, writes and
stages source files, and reads the rows the scanner prints, or the result of the
file-length gate's ratchet run over them.

Run: python3 -m unittest discover -s scripts/gates -p 'test_*.py'
"""

from __future__ import annotations

import shutil
import tempfile
import unittest
from pathlib import Path

from ratchet_harness import RatchetRepo, entry

# A file of each language and kind, with the limit its language takes.
FILES = [
    ("sdk/go/a.go", 500),
    ("sdk/go/a_test.go", 500),
    ("sdk/python/b.py", 500),
    ("sdk/python/tests/test_b.py", 500),
    ("sdk/ts/c.ts", 400),
    ("sdk/ts/tests/c.test.ts", 400),
    ("sdk/ts/d.mts", 400),
    ("scripts/e.js", 400),
    ("scripts/e.mjs", 400),
    ("website/src/lib/f.ts", 400),
    ("website/plugins/f.test.mjs", 400),
    ("website/src/components/F.astro", 400),
    ("website/brand/source/f.py", 500),
]


def lines(n: int) -> str:
    return "".join(f"x{i}\n" for i in range(n))


class FileLengthTest(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmp)
        self.repo = RatchetRepo(Path(tmp))

    def rows(self) -> list[tuple[str, str, str, str]]:
        proc = self.repo.script("file_length.py")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        rows = []
        for line in proc.stdout.splitlines():
            path, at, rule, size, message = line.split("\t", 4)
            self.assertEqual(at, "-", "a file's length is about the whole file")
            rows.append((path, rule, size, message))
        return rows

    def test_a_file_at_its_limit_passes_and_one_line_more_is_reported(self) -> None:
        for path, limit in FILES:
            self.repo.write(path, lines(limit))
        self.assertEqual(self.rows(), [])
        for path, limit in FILES:
            self.repo.write(path, lines(limit + 1))
        self.assertEqual(
            sorted(self.rows()),
            sorted(
                (path, "file-length", str(limit + 1), f"over the limit of {limit} lines")
                for path, limit in FILES
            ),
        )

    def test_a_last_line_without_a_newline_counts_and_other_breaks_do_not(self) -> None:
        self.repo.write("sdk/python/a.py", lines(500) + "tail")
        self.repo.write("sdk/python/b.py", lines(499).replace("x3\n", "x3\f\v\x1c\u2028\n"))
        self.assertEqual(
            self.rows(), [("sdk/python/a.py", "file-length", "501", "over the limit of 500 lines")]
        )

    def test_generated_untracked_and_other_files_are_not_read(self) -> None:
        header = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n"
        self.repo.write("gen/go/fora/gen.go", header + lines(600))
        self.repo.write("website/src/content/docs/f.mdx", lines(600))
        self.repo.write("sdk/go/untracked.go", lines(600), stage=False)
        self.repo.write("sdk/README.md", lines(600))
        self.assertEqual(self.rows(), [])

    def test_hand_written_code_under_gen_and_schemas_is_read(self) -> None:
        hand = "// Package schemas: the schema files are generated; this file is hand-written.\n"
        for path in (
            "schemas/schemas.go",
            "gen/jsonschema/jsonschema.go",
            "gen/python/wire/base.py",
        ):
            self.repo.write(path, hand + lines(500))
        self.assertEqual(
            [r[0] for r in self.rows()],
            ["gen/jsonschema/jsonschema.go", "gen/python/wire/base.py", "schemas/schemas.go"],
        )

    def test_a_language_without_a_limit_fails_with_its_name(self) -> None:
        # A language added to scope.py without an entry in each scanner's table
        # fails both scanners, and so both gates, in one place.
        scope = self.repo.root / "scripts" / "gates" / "scope.py"
        text = scope.read_text()
        text = text.replace('    ".sh": "shell",\n', '    ".sh": "shell",\n    ".tsx": "tsx",\n')
        text = text.replace(
            '    "shell": ("duplication",),\n',
            '    "shell": ("duplication",),\n    "tsx": _SOURCE_GATES,\n',
        )
        self.assertIn('"tsx": _SOURCE_GATES', text)
        scope.write_text(text)
        self.repo.write("sdk/ts/a.tsx", lines(3))
        for scanner in ("file_length.py", "inline_suppressions.py"):
            proc = self.repo.script(scanner)
            self.assertNotEqual(proc.returncode, 0, scanner)
            self.assertIn("KeyError: 'tsx'", proc.stderr, scanner)

    def gate(self, command: str) -> tuple[int, str]:
        proc = self.repo.gate("file-length", command)
        return proc.returncode, proc.stdout + proc.stderr

    def test_through_the_ratchet_a_grown_file_and_a_new_long_file_each_fail(self) -> None:
        self.repo.write("sdk/go/a.go", lines(520))
        self.assertEqual(self.gate("record")[0], 0)
        message = "over the limit of 500 lines"
        self.assertEqual(
            self.repo.entries(), [entry("sdk/go/a.go", "file-length", message, sizes=[520])]
        )
        self.assertEqual(self.gate("check"), (0, ""))
        self.repo.write("sdk/go/a.go", lines(521))
        code, out = self.gate("check")
        self.assertEqual(code, 1, out)
        self.assertIn("baselined findings that grew", out)
        self.assertIn("(520, 521)", out)
        self.repo.write("sdk/go/a.go", lines(520))
        self.repo.write("sdk/python/new.py", lines(501))
        code, out = self.gate("check")
        self.assertEqual(code, 1, out)
        self.assertIn("findings not in the baseline", out)
        self.assertIn("sdk/python/new.py: [file-length]", out)


if __name__ == "__main__":
    unittest.main()
