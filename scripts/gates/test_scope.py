"""Tests for scope.py, run through its command line in a throwaway git repository.

Run: python3 -m unittest discover -s scripts/gates -p 'test_*.py'
"""

from __future__ import annotations

import shutil
import tempfile
import unittest
from pathlib import Path

from ratchet_harness import GateRepo

GO_MARKER = "// Code generated by protoc-gen-go. DO NOT EDIT."
GO_HEADER = f"{GO_MARKER}\n\npackage a\n"


class ScopeTest(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmp)
        self.repo = GateRepo(Path(tmp))
        # The copied gate modules are tracked files in scope too; each test leaves
        # them out of what it compares.
        self.repo.commit("the gate modules")
        self.modules: set[str] = set()
        self.modules = set(self.files())

    def files(self, *languages: str) -> list[str]:
        args = [a for language in languages for a in ("--language", language)]
        proc = self.repo.script("scope.py", "files", *args)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        return [p for p in proc.stdout.splitlines() if p not in self.modules]

    def check(self) -> tuple[int, list[str]]:
        proc = self.repo.script("scope.py", "check")
        return proc.returncode, proc.stdout.splitlines()

    def test_every_tracked_file_of_a_gated_language_is_in_scope_by_its_suffix(self) -> None:
        paths = ("a.go", "cmd/b.py", "c.pyi", "sdk/ts/d.ts", "e.mts", "f.js", "g.mjs", "h.sh")
        for path in paths:
            self.repo.write(path, "x\n")
        self.repo.write("i.md", "x\n")
        self.repo.write("j.json", "{}\n")
        self.assertEqual(self.files(), sorted(paths))
        self.assertEqual(self.files("typescript"), ["e.mts", "sdk/ts/d.ts"])
        self.assertEqual(self.files("python", "shell"), ["c.pyi", "cmd/b.py", "h.sh"])

    def test_the_files_generated_lists_are_out(self) -> None:
        self.repo.write("gen/go/fora/v1/a.pb.go", "// a proto comment\n//\n" + GO_HEADER)
        self.repo.write("gen/python/vocab/b.py", "# Code generated by a generator. DO NOT EDIT.\n")
        self.repo.write(
            "gen/ts/strict/c.ts", "// Code generated by gen.mjs from\n// a schema. DO NOT EDIT.\n"
        )
        self.repo.write(
            "gen/python/wire/models.py", "# Code generated from the proto. DO NOT EDIT.\n"
        )
        self.assertEqual(self.files(), [])

    def test_hand_written_files_beside_generated_ones_are_in(self) -> None:
        self.repo.write("gen/go/fora/v1/a.pb.go", GO_HEADER)
        self.repo.write(
            "gen/jsonschema/jsonschema.go",
            "// The schema files are generated by a script; this file is hand-written.\n"
            "package a\n",
        )
        self.repo.write("gen/python/wire/base.py", '"""Hand-written; not regenerated."""\n')
        self.repo.write("gen/ts/wire/names.ts", "// Hand-written.\n")
        self.repo.write("schemas/schemas.go", "// The files are hand-written.\npackage schemas\n")
        self.assertEqual(
            self.files(),
            [
                "gen/jsonschema/jsonschema.go",
                "gen/python/wire/base.py",
                "gen/ts/wire/names.ts",
                "schemas/schemas.go",
            ],
        )

    def test_the_site_and_untracked_files_are_out(self) -> None:
        self.repo.write("website/src/a.ts", "x\n")
        self.repo.write("sdk/b.py", "x\n", stage=False)
        self.assertEqual(self.files(), [])

    def test_check_passes_when_generated_lists_exactly_the_files_with_a_header(self) -> None:
        code, problems = self.check()
        self.assertEqual(code, 1)
        unmatched = [p for p in problems if p.endswith("which matches no tracked file")]
        self.assertEqual(len(unmatched), len(problems))
        self.repo.write("gen/go/fora/v1/a.pb.go", GO_HEADER)
        self.assertNotIn(
            "GENERATED lists gen/go/fora/**, which matches no tracked file", self.check()[1]
        )

    def test_check_fails_on_a_listed_file_with_no_generated_header(self) -> None:
        # A hand-written file put where the generators write cannot hide there.
        self.repo.write("gen/go/fora/hand.go", "// Hand-written.\npackage fora\n")
        code, problems = self.check()
        self.assertEqual(code, 1)
        self.assertIn(
            "gen/go/fora/hand.go is listed as generated (gen/go/fora/**) "
            "but has no generated header",
            problems,
        )

    def test_check_fails_on_a_generated_file_that_generated_does_not_list(self) -> None:
        self.repo.write("sdk/go/a.go", "// a comment\n" + GO_HEADER)
        code, problems = self.check()
        self.assertEqual(code, 1)
        self.assertIn("sdk/go/a.go has a generated header but GENERATED does not list it", problems)

    def test_a_marker_below_the_opening_comments_is_not_a_header(self) -> None:
        body = "// Package a writes files.\npackage a\n\n" + GO_MARKER + "\n"
        self.repo.write("sdk/go/a.go", body)
        self.repo.write(
            "sdk/go/b.go", '// Package b.\npackage b\n\nconst h = "Code generated. DO NOT EDIT."\n'
        )
        self.assertEqual(self.files(), ["sdk/go/a.go", "sdk/go/b.go"])
        self.assertFalse([p for p in self.check()[1] if p.startswith("sdk/go/")])

    def test_an_unknown_language_is_refused(self) -> None:
        proc = self.repo.script("scope.py", "files", "--language", "rust")
        self.assertEqual(proc.returncode, 2)
        self.assertIn("invalid choice: 'rust'", proc.stderr)


if __name__ == "__main__":
    unittest.main()
