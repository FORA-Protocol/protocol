package main

import (
	"path"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// generatedHeader opens every emitted file. The gates read it to tell generated
// code from hand-written code.
const generatedHeader = "Code generated by protoc-gen-foraversion. DO NOT EDIT."

// Where the TypeScript and Python constants go, relative to the plugin's out
// directory (gen/): the wire modules of the generated types export.
const (
	tsFilename = "ts/wire/version.ts"
	pyFilename = "python/wire/version.py"
)

// emit writes the constants for every language from the one source.
func emit(gen *protogen.Plugin, src source) {
	renderGo(gen.NewGeneratedFile(goFilename(src.file), src.file.GoImportPath), src)
	renderTS(gen.NewGeneratedFile(tsFilename, ""), src)
	renderPy(gen.NewGeneratedFile(pyFilename, ""), src)
}

// goFilename puts the Go constants beside protoc-gen-go's output for the source
// file, which buf.gen.yaml lays out with paths=source_relative under gen/go:
// fora/v1/fora.proto gives go/fora/v1/fora_version.pb.go.
func goFilename(f *protogen.File) string {
	return path.Join("go", strings.TrimSuffix(f.Desc.Path(), ".proto")+"_version.pb.go")
}

func renderGo(g *protogen.GeneratedFile, src source) {
	g.P("// ", generatedHeader)
	g.P("// source: ", src.file.Desc.Path())
	g.P()
	g.P("package ", src.file.GoPackageName)
	g.P()
	g.P("// The FORA versions, authored once as file options of ", src.file.Desc.Path(), ".")
	g.P("// Its \"Protocol version\" block says what each one versions and how a receiver treats it.")
	g.P("const (")
	g.P("\t// ProtocolVersion is the value every FORA message stamps on its `ver` field:")
	g.P("\t// the (", protocolExtName, ") option.")
	g.P("\tProtocolVersion = ", strconv.Quote(src.protocol))
	g.P("\t// WellKnownManifestVersion is the version of the /.well-known/fora.json document")
	g.P("\t// layout, stamped on WellKnownManifest.ver: the (", manifestExtName, ") option.")
	g.P("\t// It is never derived from ProtocolVersion.")
	g.P("\tWellKnownManifestVersion = ", strconv.Quote(src.manifest))
	g.P(")")
}

func renderTS(g *protogen.GeneratedFile, src source) {
	g.P("// ", generatedHeader)
	g.P("// source: ", src.file.Desc.Path())
	g.P("//")
	g.P("// The FORA versions, authored once as file options of ", src.file.Desc.Path(), ".")
	g.P("// Its \"Protocol version\" block says what each one versions and how a receiver treats it.")
	g.P()
	g.P("/** The value every FORA message stamps on its `ver` field: the (", protocolExtName, ") option. */")
	g.P("export const ProtocolVersion = ", strconv.Quote(src.protocol), ";")
	g.P()
	g.P("/**")
	g.P(" * The version of the /.well-known/fora.json document layout, stamped on")
	g.P(" * WellKnownManifest.ver: the (", manifestExtName, ") option. It is never")
	g.P(" * derived from ProtocolVersion.")
	g.P(" */")
	g.P("export const WellKnownManifestVersion = ", strconv.Quote(src.manifest), ";")
}

func renderPy(g *protogen.GeneratedFile, src source) {
	g.P("# ", generatedHeader)
	g.P("# source: ", src.file.Desc.Path())
	g.P("#")
	g.P("# The FORA versions, authored once as file options of ", src.file.Desc.Path(), ".")
	g.P("# Its \"Protocol version\" block says what each one versions and how a receiver treats it.")
	g.P()
	g.P("from typing import Final")
	g.P()
	g.P("#: The value every FORA message stamps on its ``ver`` field: the")
	g.P("#: (", protocolExtName, ") option.")
	g.P("PROTOCOL_VERSION: Final = ", strconv.Quote(src.protocol))
	g.P()
	g.P("#: The version of the /.well-known/fora.json document layout, stamped on")
	g.P("#: WellKnownManifest.ver: the (", manifestExtName, ") option. It is never")
	g.P("#: derived from PROTOCOL_VERSION.")
	g.P("WELL_KNOWN_MANIFEST_VERSION: Final = ", strconv.Quote(src.manifest))
}
